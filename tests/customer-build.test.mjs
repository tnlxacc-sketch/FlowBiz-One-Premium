import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const script=fileURLToPath(new URL('../scripts/build-customer-site.mjs',import.meta.url));
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'flowbiz-customer-builder-'));
const src=path.join(tmp,'source');fs.mkdirSync(src);
const old='https://legacytest.supabase.co';
fs.writeFileSync(path.join(src,'app.js'),"const SUPABASE_URL='"+old+"';\nconst SUPABASE_KEY='sb_publishable_OLD';\nconst FLOWSTOCK_APP_URL='https://legacy.example/';\n");
fs.writeFileSync(path.join(src,'index.html'),"connect-src 'self' "+old+" wss://legacytest.supabase.co");
for(const f of ['premium.js','styles.css','master-admin-enhancements.js','master-admin-enhancements.css','support-selfservice-enhancements.js'])fs.writeFileSync(path.join(src,f),'ok');
const base=['--supabaseUrl=https://newcustomer.supabase.co','--publishableKey=sb_publishable_NEW','--siteUrl=https://customer.example/flowbiz/'];
function run(flags){return spawnSync(process.execPath,[script,...flags],{cwd:src,encoding:'utf8'});}
const target=path.join(tmp,'website');
let result=run([...base,'--output='+target]);
assert.equal(result.status,0,result.stderr);
const app=fs.readFileSync(path.join(target,'app.js'),'utf8'),html=fs.readFileSync(path.join(target,'index.html'),'utf8');
assert.match(app,/newcustomer\.supabase\.co/);assert.match(app,/customer\.example\/flowbiz/);
assert.doesNotMatch(app,/legacytest/);assert.doesNotMatch(html,/legacytest/);
assert.match(html,/wss:\/\/newcustomer\.supabase\.co/);
assert.match(fs.readFileSync(path.join(src,'app.js'),'utf8'),/legacytest/,'source unchanged');
assert.notEqual(run([...base,'--output='+target]).status,0,'cannot overwrite build');
assert.notEqual(run([...base,'--output='+path.join(src,'build')]).status,0,'cannot build into repo');
assert.notEqual(run([...base,'--publishableKey=sb_secret_TEST','--output='+path.join(tmp,'x')]).status,0,'secret key blocked');
assert.notEqual(run([...base,'--supabaseUrl=http://newcustomer.supabase.co','--output='+path.join(tmp,'y')]).status,0,'insecure URL blocked');
fs.rmSync(tmp,{recursive:true,force:true});
console.log('Customer build isolation tests passed');
